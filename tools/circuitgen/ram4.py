"""Writes examples/circuits/ram4.cli.txt (the script is the checked artifact; edit the layout here and re-run).

Usage from the repository root: python -m tools.circuitgen.ram4, then
PYTHONPATH=src python -m tools.make_circuits ram4

A 4-word x 1-bit RAM from a crossbar of literals (doc/redstone/circuits.md, "4x1 RAM").
Columns on the floor carry A1, not A1, A0, not A0, not W and D south; lines on the top
layer (y=3) run east, one READ, D and LOCK line per word, and take a literal where a
tap (a wire on the column's stone, stepping up into the line) joins them.
"""

from pathlib import Path

SCRIPT_HEAD = """# Circuit: 4x1 RAM: four 1-bit words, address A1 A0, write W, data D, output OUT. Contract:
# doc/redstone/circuits.md, "4x1 RAM". Generated by tools/circuitgen/ram4.py.
#
# Module (box 0 1 -6 .. 15 3 36):
#   @A1 0 1 -6, @A0 4 1 -6, @W 8 1 -6, @D 10 1 -6   input wires: drive them from the north
#   @OUT 15 3 35   repeater facing south: the addressed word
# How it works: the inputs become six literal columns on the floor (A1, not A1, A0, not A0,
#   not W, D; each 2 ticks late, by a repeater or a torch). Each column passes 12 crossings
#   (a repeater, a stone, then under a top-layer line); a wire on a crossing's stone steps
#   up into that line: a diode tap. Per word m: LOCK = not W or A != m holds its latch (a
#   repeater locked from the side, d_latch), D feeds it, and READ = A != m blocks its read
#   comparator (latch - 15 READ), which points into the OUT bus.
# Timing: OUT shows a word 32 ticks after the address changes (every word's read path is
#   balanced to 32, so switching between two 1s never dips). A write needs W on for 2+
#   ticks; D is sampled 2 ticks after W falls; the address must not change while W is on
#   (up to 1 tick before W falls is still safe). A written word is stored 14-32 ticks after W.
# Test harness outside the box: levers @LA1 @LA0 @LW @LD north of the inputs.
#   redsim-cli ram4.redsim.json < examples/circuits/ram4.cli.txt
new size 96 force
note "4x1 RAM: W writes D into word A1 A0; @OUT shows the addressed word 32 ticks after the address changes"
"""

# read path repeaters per word: all four words read in 32 ticks
READ_DELAYS = [(4, 4, 2), (3, 2, 2), (2, 2, 1), (1, 1, 1)]
COLS = {"A1": 0, "nA1": 2, "A0": 4, "nA0": 6, "nW": 8, "D": 10}


def mism(m):
    return ["nA1" if m >> 1 & 1 else "A1", "nA0" if m & 1 else "A0"]


def lines():
    """(row r, kind, word m, taps)"""
    out = []
    for m in range(4):
        out.append((3 * m, "READ", m, mism(m)))
        out.append((3 * m + 1, "D", m, ["D"]))
        out.append((3 * m + 2, "LOCK", m, ["nW"] + mism(m)))
    return out


def build():
    L = []
    nrows = 12
    # literal sources (north of z = 0)
    for xp in (0, 4):  # A1 and not A1, A0 and not A0
        L += [
            f"line {xp} 1 -6 to {xp} 1 -3 redstone_wire",
            f"place {xp + 1} 1 -3 redstone_wire",
            f"set {xp + 2} 1 -3 stone",
            f"place {xp + 2} 1 -2 redstone_wall_torch facing=south",
            f"place {xp} 1 -2 repeater out=south",
            f"place {xp} 1 -1 redstone_wire",
            f"place {xp + 2} 1 -1 redstone_wire",
        ]
    L += [
        "line 8 1 -6 to 8 1 -4 redstone_wire",
        "set 8 1 -3 stone",
        "place 8 1 -2 redstone_wall_torch facing=south",
        "place 8 1 -1 redstone_wire",
    ]
    L += [
        "line 10 1 -6 to 10 1 -3 redstone_wire",
        "place 10 1 -2 repeater out=south",
        "place 10 1 -1 redstone_wire",
    ]
    # crossbar
    for r in range(nrows):
        zl = 3 * r + 2
        L.append(f"fill 0 2 {zl} 11 2 {zl} stone")
        L.append(f"line 0 3 {zl} to 10 3 {zl} redstone_wire")
        for x in COLS.values():
            L += [
                f"place {x} 1 {3 * r} repeater out=south",
                f"set {x} 1 {3 * r + 1} stone",
                f"place {x} 1 {zl} redstone_wire",
            ]
    for r, _kind, _m, taps in lines():
        for t in taps:
            L.append(f"place {COLS[t]} 2 {3 * r + 1} redstone_wire")
    # word cells
    for m in range(4):
        zr = 2 + 9 * m
        z0, zL = zr + 3, zr + 6
        L += [f"fill 11 2 {zr} 13 2 {zr + 6} stone"]
        d1, d2, d3 = READ_DELAYS[m]
        L += [
            f"place 11 3 {zr} repeater out=east delay={d1}",
            f"place 12 3 {zr} repeater out=east delay={d2}",
            f"place 13 3 {zr} redstone_wire",
            f"place 13 3 {zr + 1} redstone_wire",
            f"place 13 3 {zr + 2} repeater out=south delay={d3}",
        ]
        L += [
            f"place 11 3 {z0} repeater out=east",
            f"place 12 3 {z0} repeater out=east",
            f"place 13 3 {z0} comparator out=east mode=subtract",
            f"set 14 3 {z0} stone",
        ]
        L += [
            f"place 11 3 {zL} repeater out=east",
            f"place 12 3 {zL} redstone_wire",
            f"place 12 3 {zL - 1} redstone_wire",
            f"place 12 3 {zr + 4} repeater out=north",
        ]
        L += [
            f'label Q{m} 12 3 {z0} "word {m} latch"',
            f'label G{m} 13 3 {z0} "word {m} read gate"',
        ]
    # OUT bus along x = 15 from z = 5 to z = 33, repeaters facing south at z = 18 and 31
    L.append("fill 15 2 5 15 2 35 stone")
    L.append("line 15 3 5 to 15 3 17 redstone_wire")
    L.append("place 15 3 18 repeater out=south")
    L.append("line 15 3 19 to 15 3 30 redstone_wire")
    L.append("place 15 3 31 repeater out=south")
    L.append("line 15 3 32 to 15 3 34 redstone_wire")
    L.append("place 15 3 35 repeater out=south")
    return L


