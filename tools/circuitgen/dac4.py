"""Writes examples/circuits/dac4.cli.txt (the script is the checked artifact; edit the layout here and re-run).

Usage from the repository root: python -m tools.circuitgen.dac4, then
PYTHONPATH=src python -m tools.make_circuits dac4.
`python -m tools.circuitgen.dac4 --all FILE` writes a variant with all 240 transitions
between two values (each must jump straight from the old value to the new one) to FILE.
"""

import sys
from pathlib import Path

BITS = ["B0", "B1", "B2", "B3"]

LAYOUT = """source -1 1 0 barrel 15
place 0 1 0 comparator out=east mode=subtract
place 1 1 0 comparator out=east mode=subtract
place 2 1 0 comparator out=east mode=subtract
place 3 1 0 comparator out=east mode=subtract
set 4 1 0 stone
# bit 3 (8): gate 0 1 -2 = barrel 8 - B3, one wire cell into K3's side
source 0 1 -3 barrel 8
place 0 1 -2 comparator out=south mode=subtract
place 0 1 -1 redstone_wire
place -1 1 -2 repeater out=east delay=1
# bit 2 (4): gate 1 1 2 = barrel 4 - B2, one wire cell into K2's side
source 1 1 3 barrel 4
place 1 1 2 comparator out=north mode=subtract
place 1 1 1 redstone_wire
place 0 1 2 repeater out=east delay=2
# bit 1 (2): gate 2 1 -4 = barrel 4 - B1, three wire cells (4, 3, 2) into K1's side
source 2 1 -5 barrel 4
place 2 1 -4 comparator out=south mode=subtract
line 2 1 -3 to 2 1 -1 redstone_wire
place 1 1 -4 repeater out=east delay=3
# bit 0 (1): gate 3 1 4 = barrel 3 - B0, three wire cells (3, 2, 1) into K0's side
source 3 1 5 barrel 3
place 3 1 4 comparator out=north mode=subtract
line 3 1 3 to 3 1 1 redstone_wire
place 2 1 4 repeater out=east delay=4
# input wires from the west edge (x = -1) to the repeaters of bits 2, 1 and 0
place -1 1 2 redstone_wire
line -1 1 -4 to 0 1 -4 redstone_wire
line -1 1 4 to 1 1 4 redstone_wire"""

HEAD = """# Circuit: 4-bit DAC (binary to signal strength): OUT = 8*B3 + 4*B2 + 2*B1 + B0. Contract:
# doc/redstone/circuits.md, "4-bit DAC". Generated by tools/circuitgen/dac4.py.
#
# Module (box -1 1 -5 .. 4 1 5):
#   @B3  -1 1 -2  bit 3: the repeater (delay 1) at the west edge; drive it from the west
#   @B2  -1 1 2   bit 2: wire at the west edge (to a delay-2 repeater); drive it from the west
#   @B1  -1 1 -4  bit 1: wire (to a delay-3 repeater); drive it from the west
#   @B0  -1 1 4   bit 0: wire (to a delay-4 repeater); drive it from the west
#   @OUT 4 1 0    stone powered with N by the comparator 3 1 0: read it from the east
# How it works (all comparators subtract): the chain K3..K0 (0..3 1 0) starts from a full
#   barrel (15) and subtracts the weight of every bit that is OFF: 15 - (15 - N) = N. Each
#   weight comes from a gate comparator reading a barrel and blocked by its bit (side 15):
#   barrel w - B = w while the bit is off, 0 while on. The gates of bits 1 and 0 sit two
#   cells further out (three wire cells lose 2, so their barrels hold w + 2), which leaves
#   every input reachable from the west edge and the east side clear for the reader.
# Latency 12 ticks from every bit (the repeaters' delays 1..4 balance the chain), so
#   several bits may change together: OUT jumps straight to the new value.
# Test harness outside the box: levers @L0..@L3 west of the inputs.
#   redsim-cli dac4.redsim.json < examples/circuits/dac4.cli.txt
new size 32 force
note "4-bit DAC: @OUT (the stone 4 1 0) is powered with N = 8 B3 + 4 B2 + 2 B1 + B0, 12 ticks after any input"
"""

TAIL = """label B3 -1 1 -2 "bit 3 (8): repeater at the west edge, driven from the west"
label B2 -1 1 2 "bit 2 (4): wire at the west edge, driven from the west"
label B1 -1 1 -4 "bit 1 (2): wire at the west edge, driven from the west"
label B0 -1 1 4 "bit 0 (1): wire at the west edge, driven from the west"
label OUT 4 1 0 "output: a stone powered with N"
label K0 3 1 0 "last chain comparator (its output is N)"
group dac4 -1 1 -5 4 1 5 in @B0 B0 in @B1 B1 in @B2 B2 in @B3 B3 out @OUT OUT
settle
prefab save dac4 -1 1 -5 4 1 5
# harness
place -2 1 -2 lever face=floor
place -2 1 2 lever face=floor
place -2 1 -4 lever face=floor
place -2 1 4 lever face=floor
place 5 1 0 comparator out=east
place 6 1 0 redstone_lamp
label L3 -2 1 -2 "test lever B3"
label L2 -2 1 2 "test lever B2"
label L1 -2 1 -4 "test lever B1"
label L0 -2 1 4 "test lever B0"
label READ 5 1 0 "reader: a comparator after OUT"
settle
"""


def levers(a: int, b: int, t: str, at: int) -> list[str]:
    out = [f"target {t} do use @L{i}" for i in range(4) if a >> i & 1]
    out += [f"target {t} do at {at} use @L{i}" for i in range(4) if (a ^ b) >> i & 1]
    return out


def targets(all_transitions: bool) -> list[str]:
    out = [
        "",
        'target new values "counting 0..15, one step every 16 ticks from 26 (7 -> 8 flips all four bits): OUT reaches every value 12 ticks after its step, never anything else"',
    ]
    for k in range(1, 16):
        out += [
            f"target values do at {10 + 16 * k} use @L{i}"
            for i in range(4)
            if ((k - 1) ^ k) >> i & 1
        ]
    out.append("target values expect @OUT power=0 during 0..37")
    for k in range(1, 16):
        end = 10 + 16 * (k + 1) + 11 if k < 15 else 290
        out.append(f"target values expect @OUT power={k} during {10 + 16 * k + 12}..{end}")
    pairs = (
        [(a, b) for a in range(16) for b in range(16) if a != b]
        if all_transitions
        else [(n, 15 - n) for n in range(16)]
    )
    out += [
        "",
        "# every bit flips at once (N -> 15 - N): OUT jumps straight from N to 15 - N at 42",
    ]
    for a, b in pairs:
        t = f"t{a}_{b}"
        out.append(f'target new {t} "{a} -> {b} at 30: {a} until 41, {b} from 42"')
        out += levers(a, b, t, 30)
        out += [
            f"target {t} expect @OUT power={a} during 20..41",
            f"target {t} expect @OUT power={b} during 42..60",
        ]
    out += [
        "",
        'target new unbalanced "failure case: all four input repeaters at delay 1 (bit 0 then takes 6 ticks, bit 3 12): 0 -> 9 at 30 shows 1 for 6 ticks first"',
    ]
    out += [
        f"target unbalanced do set {p} repeater facing={f} delay=1"
        for p, f in (("-1 1 -2", "west"), ("0 1 2", "west"), ("1 1 -4", "west"), ("2 1 4", "west"))
    ]
    out += [
        "target unbalanced do at 30 use @L0",
        "target unbalanced do at 30 use @L3",
        "target unbalanced expect @OUT power=0 during 20..35",
        "target unbalanced expect @OUT power=1 during 36..41",
        "target unbalanced expect @OUT power=9 during 42..60",
        "",
        "check",
    ]
    return out


def script(all_transitions: bool = False) -> str:
    return HEAD + LAYOUT + "\n" + TAIL + "\n".join(targets(all_transitions)) + "\n"


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--all":
        Path(sys.argv[2]).write_text(script(True))
    else:
        (Path(__file__).resolve().parents[2] / "examples" / "circuits" / "dac4.cli.txt").write_text(
            script()
        )
