"""Writes examples/circuits/instant_wire.cli.txt (the script is the checked artifact; edit the layout here and re-run).

Usage from the repository root: python -m tools.circuitgen.instant_wire [STAGES], then
PYTHONPATH=src python -m tools.make_circuits instant_wire

STAGES (default 2) is the number of 17-block stages between the head and the tail: the
module is 17 * STAGES + 5 blocks long, OUT rises at once, and it falls (and the module is
armed again) 3 * (STAGES + 2) ticks after IN goes off.
"""

import sys
from pathlib import Path


def layout(stages: int) -> tuple[list[str], int]:
    """The module's build lines (record R-023, row C, with wire lines between the stages)
    and x of its tail piston."""
    out = [
        "# head: IN stone 0 2 2 behind the head piston; the redstone block 0 2 0 in front of",
        "# it powers the first stage's piston 1 2 0 from behind",
        "set 0 2 2 stone",
        "set 0 2 0 redstone_block",
        "place 0 2 1 sticky_piston facing=north",
    ]
    for j in range(stages):
        x = 1 + 17 * j
        out += [
            f"# stage {j}: piston {x} 2 0, its redstone block lands on {x + 2} 2 0 and powers the wire {x + 3}..{x + 16}",
            f"set {x + 1} 2 0 redstone_block",
            f"fill {x + 3} 1 0 {x + 16} 1 0 stone",
            f"line {x + 3} 2 0 to {x + 16} 2 0 redstone_wire",
            f"place {x} 2 0 sticky_piston facing=east",
        ]
    t = 1 + 17 * stages
    out += [
        f"# tail: piston {t} 2 0 holds the stone {t + 2} 2 0 over the step from the wire {t + 3} 2 0",
        f"# (fed by the redstone block {t + 4} 2 0) down to the output wire {t + 2} 1 0",
        f"set {t + 1} 2 0 stone",
        f"set {t + 3} 1 0 stone",
        f"set {t + 4} 2 0 redstone_block",
        f"place {t + 3} 2 0 redstone_wire",
        f"line {t + 2} 1 0 to {t + 2} 1 2 redstone_wire",
        f"place {t} 2 0 sticky_piston facing=east",
    ]
    return out, t


def script(stages: int) -> str:
    body, t = layout(stages)
    rearm = 3 * (stages + 2)
    length = t + 5
    head = f"""# Circuit: instant wire (OUT rises in the same tick as IN, {length} blocks away). Contract:
# doc/redstone/circuits.md, "Instant wire"; the mechanism is record R-023 (game-verified).
# Generated by tools/circuitgen/instant_wire.py ({stages} stages; any number works).
#
# Module (box 0 1 -1 .. {t + 4} 2 2; it rests on the floor, y=0):
#   @IN   0 2 2    a stone behind the head piston: power it (lever on it, repeater or wire into it)
#   @OUT  {t + 2} 1 2   wire at the south edge, strength 12
# How it works: a chain of extended sticky pistons, each holding a redstone block that
#   powers the next one (directly, or through a 14-wire line), collapses in the same
#   block-event phase when its first piston loses power: every piston it depowers queues
#   its retract into the phase being run. IN makes the head piston push the first block
#   away (the rising edge starts the collapse); the tail piston then pulls its stone off
#   the step from the wire {t + 3} 2 0 down to the output wire, which lights at once.
# Timing: OUT on in the tick the head moves: the same tick as IN when a component powers
#   it, one tick later from a lever (as every piston). OUT off {rearm} ticks after IN goes
#   off (each stage re-extends 3 ticks after the one before): that is also how long IN must
#   stay off before the next instant edge. IN pulses must last 3+ ticks (a shorter one
#   makes the head spit its block, and the chain stays down until the next cycle).
# Test harness outside the box: lever on IN; a repeater driven by a lever (south of IN).
#   redsim-cli instant_wire.redsim.json < examples/circuits/instant_wire.cli.txt
new size 96 force
note "Instant wire: @OUT rises in the same tick as @IN, {length} blocks away; it falls {rearm} ticks after IN (re-arming)"
"""
    tail = f"""label IN 0 2 2 "input: a stone behind the head piston; power it"
label OUT {t + 2} 1 2 "output: wire, rises in the head's tick"
label HEAD 0 2 1 "head piston"
label W0 4 2 0 "first wire of stage 0"
label CUT {t + 2} 2 0 "the stone over the output step while armed"
settle
group instant_wire 0 1 -1 {t + 4} 2 2 in @IN IN out @OUT OUT
prefab save instant_wire 0 1 -1 {t + 4} 2 2
# harness: a lever on IN; a lever -> repeater (delay 1) into IN from the south
place 0 3 2 lever face=floor
label LIN 0 3 2 "test lever on IN"
set 0 1 3 stone
set 0 1 4 stone
place 0 2 3 repeater out=north
place 0 2 4 lever face=floor
label LREP 0 2 4 "test lever behind the repeater"
label REP 0 2 3 "repeater into IN"
settle

target new instant "lever on IN at 10: the head moves at 11, and the whole chain with it: OUT and the first stage change at 11"
target instant do at 10 use @LIN
target instant expect @OUT power=0 during 0..10
target instant expect @OUT power>=1 during 11..40
target instant expect @W0 power>=1 during 0..10
target instant expect @W0 power=0 during 11..40

target new same_tick "a repeater powers IN: OUT rises in the tick the repeater turns on (12), 0 ticks after it"
target same_tick do at 10 use @LREP
target same_tick expect @REP powered=false during 0..11
target same_tick expect @REP powered=true during 12..40
target same_tick expect @OUT power=0 during 0..11
target same_tick expect @OUT power>=1 during 12..40

target new rearm "IN on at 10 (OUT 11), off at 30: OUT off at {30 + rearm}, after the chain has re-extended; on again at {32 + rearm} (OUT {33 + rearm})"
target rearm do at 10 use @LIN
target rearm do at 30 use @LIN
target rearm do at {32 + rearm} use @LIN
target rearm expect @OUT power>=1 during 11..{29 + rearm}
target rearm expect @OUT power=0 during {30 + rearm}..{32 + rearm}
target rearm expect @OUT power>=1 during {33 + rearm}..{60 + rearm}

target new too_soon "failure case: IN back on {rearm - 2} ticks after it went off, while the tail's stone is still moving: the tail spits it onto the step, and OUT goes off while IN is on"
target too_soon do at 10 use @LIN
target too_soon do at 30 use @LIN
target too_soon do at {28 + rearm} use @LIN
target too_soon expect @OUT power>=1 during 11..{28 + rearm}
target too_soon expect @OUT power=0 during {29 + rearm}..{50 + rearm}

target new short_pulse "failure case: a 2-tick pulse on IN makes the head spit its block: the chain stays down (OUT on) until IN has been on and off again"
target short_pulse do at 10 use @LIN
target short_pulse do at 12 use @LIN
target short_pulse expect @OUT power>=1 during 11..60

check
"""
    return head + "\n".join(body) + "\n" + tail


if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    (
        Path(__file__).resolve().parents[2] / "examples" / "circuits" / "instant_wire.cli.txt"
    ).write_text(script(n))
