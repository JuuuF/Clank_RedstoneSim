"""Writes examples/circuits/seg7.cli.txt and adc4.cli.txt: lookup tables on decoder16.

Usage from the repository root: python -m tools.circuitgen.rom16, then
PYTHONPATH=src python -m tools.make_circuits seg7 adc4

A 16-word lookup table (doc/redstone/circuits.md, "Lookup table"): decoder16 gives one
line per value 0..15 (fed by dac4 for a binary input); its outputs, north and south of
it, turn east one by one (the easternmost first, so no two cross) into 16 rows on the
floor; the rows cross the output lines on the top layer (y=3), and a tap (a wire on the
crossing's stone, stepping up into the line) puts a value on every line whose bit is set.
"""

from pathlib import Path

#: segments a..g as bits 0..6 for the hex digits 0..F
SEG7 = [
    0x3F,
    0x06,
    0x5B,
    0x4F,
    0x66,
    0x6D,
    0x7D,
    0x07,
    0x7F,
    0x6F,
    0x77,
    0x7C,
    0x39,
    0x5E,
    0x79,
    0x71,
]
X0 = 22  # first crossing column of the OR plane


def rows() -> list[tuple[int, int, int, str]]:
    """(value m, decoder output x, row z, side) for the 16 decoder outputs (decoder16 at 4 1 -4)."""
    out = []
    for m in range(16):
        x = m + 5 if m else 6
        if m % 2 == 0:
            out.append((m, x, -6 - 2 * ((14 - m) // 2), "north"))
        else:
            out.append((m, x, 6 + 2 * ((15 - m) // 2), "south"))
    return out


def turns() -> list[str]:
    """Each decoder output: a repeater out of the decoder, a wire to its row, a corner,
    a repeater facing east, a wire to the OR plane. Two repeaters on every path."""
    L = []
    for m, x, z, side in rows():
        s = -1 if side == "north" else 1
        out_dir = "north" if side == "north" else "south"
        if m == 0:  # O0 sits beside O2: a stone on its output cell powers the wire west of it
            L += [
                "set 6 1 -5 stone",
                "place 5 1 -5 redstone_wire",
                "place 5 1 -6 repeater out=north",
            ]
            L.append(f"line 5 1 -7 to 5 1 {z} redstone_wire")
            x = 5
        else:
            L.append(f"place {x} 1 {5 * s} repeater out={out_dir}")
            L.append(f"line {x} 1 {6 * s} to {x} 1 {z} redstone_wire")
        L.append(f"place {x + 1} 1 {z} repeater out=east")
        if x + 2 <= X0 - 1:
            L.append(f"line {x + 2} 1 {z} to {X0 - 1} 1 {z} redstone_wire")
    return L


def or_plane(table: list[int], bits: int) -> list[str]:
    L = []
    zs = [z for _, _, z, _ in rows()]
    for k in range(bits):
        xr, xk, xl = X0 + 3 * k, X0 + 3 * k + 1, X0 + 3 * k + 2
        # output line k on the top layer, z = -21 .. 21, repeaters facing south at -7, 7, 21
        # (between rows; every segment's farthest tap still reaches the next repeater)
        L.append(f"fill {xl} 2 -21 {xl} 2 21 stone")
        for a, b in ((-21, -8), (-6, 6), (8, 20)):
            L.append(f"line {xl} 3 {a} to {xl} 3 {b} redstone_wire")
        L += [
            f"place {xl} 3 -7 repeater out=south",
            f"place {xl} 3 7 repeater out=south",
            f"place {xl} 3 21 repeater out=south",
        ]
        for z in zs:
            L += [
                f"place {xr} 1 {z} repeater out=east",
                f"set {xk} 1 {z} stone",
                f"place {xl} 1 {z} redstone_wire",
            ]
        for m, _, z, _ in rows():
            if table[m] >> k & 1:
                L.append(f"place {xk} 2 {z} redstone_wire")
    return L


SEG7_HEAD = """# Circuit: hex 7-segment decoder: four bits in, the seven segment lines a..g out. Contract:
# doc/redstone/circuits.md, "Lookup table". Generated by tools/circuitgen/rom16.py; run from
# the repository root (it imports decoder16.nbt and dac4.nbt, as bin_decoder16 does).
#
#   @L0..@L3      levers on the four bits (dac4's inputs, at x = -2)
#   @Sa..@Sg      the segment lines: repeaters facing south at 22+3k 3 21 (a = k 0 ... g = k 6)
# Digits: 0 abcdef, 1 bc, 2 abdeg, 3 abcdg, 4 bcfg, 5 acdfg, 6 acdefg, 7 abc, 8 all, 9 abcdfg,
#   A abcefg, b cdefg, C adef, d bcdeg, E adefg, F aefg.
# How it works: bin_decoder16 (dac4 + decoder16) turns the bits into one line per value;
#   each line turns east into a row on the floor (rows z = -20..-6 and 6..20); every row
#   crosses the seven segment lines (top layer, x = 24, 27, ... 42) and taps the segments
#   its digit lights.
# Timing: the segments are settled 46 ticks after the bits change (22 for bin_decoder16, 4
#   for the turns, 2 per crossing, 2-6 along the segment line); from 30 ticks on they may
#   flicker until then. Module box -1 1 -21 .. 42 3 21 (pasteable: seg7.nbt; the inputs are
#   dac4's, at x = -1).
#   redsim-cli seg7.redsim.json < examples/circuits/seg7.cli.txt
new size 112 force
note "Hex 7-segment decoder: levers @L0..@L3 (binary), segment lines @Sa..@Sg (south end, x = 24..42), settled 46 ticks after a change"
import examples/circuits/decoder16.nbt at 4 1 -4
import examples/circuits/dac4.nbt at -1 1 -5
place -2 1 -2 lever face=floor
place -2 1 2 lever face=floor
place -2 1 -4 lever face=floor
place -2 1 4 lever face=floor
label L3 -2 1 -2 "bit 3 (lever)"
label L2 -2 1 2 "bit 2 (lever)"
label L1 -2 1 -4 "bit 1 (lever)"
label L0 -2 1 4 "bit 0 (lever)"
"""

ADC_HEAD = """# Circuit: 4-bit ADC: a signal strength in, its value as four bits out. Contract:
# doc/redstone/circuits.md, "Lookup table". Generated by tools/circuitgen/rom16.py; run from
# the repository root (it imports decoder16.nbt).
#
#   @IN           decoder16's input barrel 4 1 0 (any container or powered block there)
#   @B0..@B3      the bits: repeaters facing south at 22+3k 3 21 (B0 = k 0 ... B3 = k 3)
# How it works: decoder16 gives one line per strength; each line turns east into a row on
#   the floor and taps the bit lines (top layer, x = 24, 27, 30, 33) of its value's 1 bits.
# Timing: the bits are settled 28 ticks after the strength changes (10 for decoder16, 4 for
#   the turns, 2 per crossing, 2-6 along the bit line); from 18 ticks on they may flicker
#   until then. Module box 4 1 -21 .. 33 3 21 (pasteable: adc4.nbt).
#   redsim-cli adc4.redsim.json < examples/circuits/adc4.cli.txt
new size 112 force
note "4-bit ADC: the strength in barrel @IN as bits @B0..@B3, settled 28 ticks after it changes"
import examples/circuits/decoder16.nbt at 4 1 -4
label IN 4 1 0 "input: decoder16's barrel"
"""


def seg7() -> str:
    names = "abcdefg"
    L = [SEG7_HEAD.rstrip("\n")] + turns() + or_plane(SEG7, 7)
    L += [f'label S{names[k]} {X0 + 3 * k + 2} 3 21 "segment {names[k]}"' for k in range(7)]
    L += [
        'label B3 -1 1 -2 "bit 3 (8): dac4\'s input"',
        'label B2 -1 1 2 "bit 2 (4)"',
        'label B1 -1 1 -4 "bit 1 (2)"',
        'label B0 -1 1 4 "bit 0 (1)"',
    ]
    L.append("settle")
    L.append(
        "group seg7 -1 1 -21 42 3 21 in @B0 B0 in @B1 B1 in @B2 B2 in @B3 B3 "
        + " ".join(f"out @S{c} {c}" for c in names)
    )
    L.append("prefab save seg7 -1 1 -21 42 3 21")
    rows_ = " ".join(
        "".join(str(n >> i & 1) for i in range(4))
        + ":"
        + "".join(str(SEG7[n] >> k & 1) for k in range(7))
        for n in range(16)
    )
    outs = " ".join(f"@S{c}" for c in names)
    L += [
        "",
        'target new digits "each of the 16 inputs lights its digit\'s segments"',
        f"target digits truth @L0 @L1 @L2 @L3 -> {outs} rows {rows_} settle 60",
        "",
        "check",
    ]
    return "\n".join(L) + "\n"


def adc4() -> str:
    L = [ADC_HEAD.rstrip("\n")] + turns() + or_plane(list(range(16)), 4)
    L += [f'label B{k} {X0 + 3 * k + 2} 3 21 "bit {k}"' for k in range(4)]
    L += ["set 4 1 0 stone", "set 4 1 0 barrel", "settle"]  # an empty barrel: strength 0
    L.append(
        "group adc4 4 1 -21 33 3 21 in @IN IN " + " ".join(f"out @B{k} B{k}" for k in range(4))
    )
    L += ["prefab save adc4 4 1 -21 33 3 21", ""]
    seq = [0, 5, 10, 15, 3, 12, 7, 8, 1, 14, 6, 9, 2, 13, 4, 11]
    L.append(
        'target new values "the barrel steps through all 16 strengths, one every 50 ticks: the bits show each value from 40 ticks after its step until 15 ticks after the next"'
    )
    for i, n in enumerate(seq[1:], 1):  # seq[0] = 0 is the empty barrel of the build
        L.append(f"target values do at {10 + 50 * i} source 4 1 0 barrel {n}")
    for i, n in enumerate(seq):
        lo, hi = 10 + 50 * i + 40, 10 + 50 * (i + 1) + 15  # until the next value may arrive
        for k in range(4):
            L.append(
                f"target values expect @B{k} powered={'true' if n >> k & 1 else 'false'} during {lo}..{hi}"
            )
    L += ["", "check"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2] / "examples" / "circuits"
    (root / "seg7.cli.txt").write_text(seg7())
    (root / "adc4.cli.txt").write_text(adc4())
