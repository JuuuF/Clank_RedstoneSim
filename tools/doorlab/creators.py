"""The corpus by creator (``python -m tools.doorlab.creators``): writes
``doc/redstone/doors/creators.md`` from the inventory, the mechanism census
(``experiments/doors/patterns.json``) and the analyses index: per creator, their worlds,
what each demonstrates (the census mechanisms with counts, the analysis page's notes),
and the reverse index technique → creators. Attribution is the mission's rule: every
technique links to the world that shows it and names its creator as recorded in the
world's title.
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
INVENTORY = ROOT / "experiments" / "doors" / "inventory.json"
PATTERNS = ROOT / "experiments" / "doors" / "patterns.json"
ANALYSES = ROOT / "doc" / "redstone" / "doors" / "analyses" / "README.md"
OUT = ROOT / "doc" / "redstone" / "doors" / "creators.md"

#: census column → (name of the technique, pattern-library section)
TECHNIQUES = {
    "spits": ("spits (a short pulse places a block and leaves it)", "Spits"),
    "qc": ("quasi-connectivity power", "Quasi-connectivity (QC) power"),
    "landings": ("landing checks (a moved piston fires by itself)", "Landing checks"),
    "switches": ("power switches (moving the conductor)", "Power switches"),
    "observers_moved": ("moving observers (sliders)", "Moving power sources"),
    "rb_moved": ("moving redstone blocks (block swappers)", "Moving power sources"),
    "slime_moved": ("slime / honey assemblies", "Slime and honey assemblies"),
}
NOT_INVESTIGATED = {"7x7-piston-door-legden", "8x8-piston-door-legden"}


def analyses_index() -> dict[str, tuple[str, str]]:
    """slug → (explained, notes) from the analyses README table (a row may name two)."""
    out: dict[str, tuple[str, str]] = {}
    for line in ANALYSES.read_text().split("\n"):
        if not line.startswith("| [["):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 3:
            continue
        for slug in re.findall(r"\[\[([^\]]+)\]\]", cells[0]):
            out[slug] = (cells[1].replace("*", ""), cells[2])
    return out


def main() -> None:
    inventory = json.loads(INVENTORY.read_text())["worlds"]
    census = {c["world"]: c for c in json.loads(PATTERNS.read_text())}
    index = analyses_index()
    by_creator: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for w in inventory:
        by_creator[w["creator"]].append(w)
    technique_creators: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    lines = [
        "# The corpus by creator",
        "",
        "Generated by `python -m tools.doorlab.creators` from [[inventory]], the mechanism",
        "census ([[patterns]]) and [[analyses/README]]. The creator is the name in the world's",
        "title; nothing here is attributed beyond what the world shows. Counts are per designed",
        'run (replay); "explained" means a hand-written analysis page exists.',
        "",
        "## Creators",
        "",
    ]
    for creator in sorted(by_creator, key=str.lower):
        worlds = sorted(by_creator[creator], key=lambda w: w["id"])
        lines.append(f"### {creator}")
        lines.append("")
        lines.append("| World | Doorway | Explained | Demonstrates (census) | Notes (analysis) |")
        lines.append("|---|---|---|---|---|")
        for w in worlds:
            slug = w["id"]
            c = census.get(slug, {})
            shows = []
            for key, (name, _) in TECHNIQUES.items():
                n = c.get(key, 0)
                if n:
                    shows.append(f"{name.split(' (')[0]} {n}")
                    technique_creators[name][creator].append(slug)
            if c.get("depth", 1) and c.get("depth", 1) > 1:
                shows.append(f"extender depth {c['depth']}")
                technique_creators["extenders (stacked pistons)"][creator].append(slug)
            groups = ", ".join(f"{g} {n}" for g, n in (c.get("groups") or {}).items())
            if groups:
                shows.append(f"exits: {groups}")
            explained, notes = index.get(slug, ("facts", ""))
            if slug in NOT_INVESTIGATED:
                notes = "not investigated (the owner's rule; moved to `broken_doors/`)"
            lines.append(
                f"| [[analyses/{slug}]] | {c.get('door') or w.get('nominal_size') or '—'} | "
                f"{explained} | {'; '.join(shows) or '—'} | {notes} |"
            )
        lines.append("")
    lines += ["## Techniques → creators", "", "| Technique | Creators (worlds) |", "|---|---|"]
    for name in sorted(technique_creators):
        who = "; ".join(
            f"{creator} ({', '.join(f'[[analyses/{s}]]' for s in sorted(slugs))})"
            for creator, slugs in sorted(
                technique_creators[name].items(), key=lambda kv: kv[0].lower()
            )
        )
        lines.append(f"| {name} | {who} |")
    lines += [
        "",
        "Design principles and the mechanisms' explanations, with the worlds that support",
        "each, are in [[patterns]]; what each door tolerates in [[robustness]]; the measured",
        "goals in [[metrics]].",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(by_creator)} creators, {len(inventory)} worlds")


if __name__ == "__main__":
    main()
